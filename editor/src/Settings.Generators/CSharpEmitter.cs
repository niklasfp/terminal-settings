using System.Globalization;
using System.Linq;
using System.Text;

namespace Settings.Generators;

/// <summary>Emits the typed descriptor table the server validates and converts values with.</summary>
internal static class CSharpEmitter
{
    public static string Emit(SchemaDoc schema)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/> by Settings.Generators from the schema files under schema/");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("namespace Settings.Generated;");
        sb.AppendLine();
        sb.AppendLine("internal static partial class AppSchema");
        sb.AppendLine("{");
        sb.Append("    public const string Revision = ").Append(Lit(schema.Revision)).AppendLine(";");
        sb.AppendLine();
        sb.AppendLine("    public static readonly global::Settings.Core.SettingGroup[] Groups =");
        sb.AppendLine("    [");
        foreach (var g in schema.Groups)
            sb.Append("        new(").Append(Lit(g.Id)).Append(", ").Append(Lit(g.Title)).AppendLine("),");
        sb.AppendLine("    ];");
        sb.AppendLine();
        sb.AppendLine("    public static readonly global::Settings.Core.Setting[] Settings =");
        sb.AppendLine("    [");
        foreach (var s in schema.Settings)
        {
            sb.Append("        new(").Append(Lit(s.Key)).Append(", global::Settings.Core.SettingType.").Append(TypeName(s.Type)).AppendLine(")");
            sb.AppendLine("        {");
            sb.Append("            Group = ").Append(Lit(s.Group)).AppendLine(",");
            sb.Append("            Label = ").Append(Lit(s.Label)).AppendLine(",");
            if (s.Min is { } min) sb.Append("            Min = ").Append(Num(min)).AppendLine(",");
            if (s.Max is { } max) sb.Append("            Max = ").Append(Num(max)).AppendLine(",");
            if (s.Nullable) sb.AppendLine("            Nullable = true,");
            if (s.Overridable) sb.AppendLine("            Overridable = true,");
            if (s.Repeatable) sb.AppendLine("            Repeatable = true,");
            if (s.Values is { } values)
                sb.Append("            Values = [").Append(string.Join(", ", values.Select(Lit))).AppendLine("],");
            if (s.Fields is { } fields)
            {
                sb.Append("            Fields = [");
                sb.Append(string.Join(", ", fields.Select(f =>
                    $"new({Lit(f.Key)}, global::Settings.Core.SettingType.{TypeName(f.Type)})")));
                sb.AppendLine("],");
            }
            sb.Append("            DefaultJson = ").Append(Lit(MiniJson.Write(s.Default))).AppendLine(",");
            sb.AppendLine("        },");
        }
        sb.AppendLine("    ];");
        sb.AppendLine("}");
        return sb.ToString();
    }

    internal static string TypeName(string type) => type switch
    {
        "fontStyle" => "FontStyle",
        _ => char.ToUpperInvariant(type[0]) + type.Substring(1),
    };

    static string Num(double d) => d.ToString("R", CultureInfo.InvariantCulture);

    internal static string Lit(string s)
    {
        var sb = new StringBuilder("\"");
        foreach (char c in s)
        {
            switch (c)
            {
                case '"': sb.Append("\\\""); break;
                case '\\': sb.Append("\\\\"); break;
                case '\n': sb.Append("\\n"); break;
                case '\r': sb.Append("\\r"); break;
                case '\t': sb.Append("\\t"); break;
                default:
                    if (c < 0x20) sb.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                    else sb.Append(c);
                    break;
            }
        }
        return sb.Append('"').ToString();
    }
}

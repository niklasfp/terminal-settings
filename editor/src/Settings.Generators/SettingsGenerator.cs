using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Settings.Generators;

/// <summary>
/// Reads a terminal's schema files (one generated from its source, one hand-written overlay)
/// and generates the settings descriptors plus the complete settings page as Settings.Generated.AppSchema.
/// The file names decide which terminal's merger runs.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class SettingsGenerator : IIncrementalGenerator
{
    const string Category = "SettingsSchema";

    // (source file, overlay file, merger) per supported terminal.
    static readonly (string Source, string Overlay, Func<string, string, List<SchemaDiagnostic>, SchemaDoc> Merge)[] Terminals =
    {
        ("rio-source.json", "rio-overlay.json", RioSchemaMerger.Merge),
        ("ghostty-source.json", "ghostty-overlay.json", GhosttySchemaMerger.Merge),
    };

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var names = new HashSet<string>(Terminals.SelectMany(t => new[] { t.Source, t.Overlay }));
        var files = context.AdditionalTextsProvider
            .Where(f => names.Contains(Path.GetFileName(f.Path)))
            .Select((f, ct) => (name: Path.GetFileName(f.Path), text: f.GetText(ct)?.ToString() ?? ""))
            .Collect();

        context.RegisterSourceOutput(files, static (spc, inputs) =>
        {
            var terminal = Terminals.FirstOrDefault(t => inputs.Any(i => i.name == t.Source));
            var source = inputs.FirstOrDefault(i => i.name == terminal.Source).text;
            var overlay = inputs.FirstOrDefault(i => i.name == terminal.Overlay).text;
            if (terminal.Merge is null || string.IsNullOrEmpty(source) || string.IsNullOrEmpty(overlay))
            {
                spc.ReportDiagnostic(Diagnostic.Create(
                    new DiagnosticDescriptor("SET000", "Schema files missing",
                        "Add a <terminal>-source.json and <terminal>-overlay.json pair as AdditionalFiles", Category, DiagnosticSeverity.Error, true),
                    Location.None));
                return;
            }

            var diags = new List<SchemaDiagnostic>();
            SchemaDoc schema;
            try
            {
                schema = terminal.Merge(source, overlay, diags);
            }
            catch (Exception ex)
            {
                spc.ReportDiagnostic(Diagnostic.Create(
                    new DiagnosticDescriptor("SET009", "Schema could not be read", "{0}", Category, DiagnosticSeverity.Error, true),
                    Location.None, ex.Message));
                return;
            }

            foreach (var d in diags)
            {
                spc.ReportDiagnostic(Diagnostic.Create(
                    new DiagnosticDescriptor(d.Id, "Settings schema", "{0}", Category,
                        d.IsError ? DiagnosticSeverity.Error : DiagnosticSeverity.Warning, true),
                    Location.None, d.Message));
            }
            if (diags.Any(d => d.IsError)) return;

            spc.AddSource("AppSchema.g.cs", SourceText.From(CSharpEmitter.Emit(schema), Encoding.UTF8));
            spc.AddSource("AppSchema.Html.g.cs", SourceText.From(EmitHtml(HtmlEmitter.Emit(schema)), Encoding.UTF8));
        });
    }

    static string EmitHtml(string html)
    {
        // A raw string literal needs a longer quote run than any inside the content.
        int longest = 0, run = 0;
        foreach (char c in html)
        {
            run = c == '"' ? run + 1 : 0;
            if (run > longest) longest = run;
        }
        var quotes = new string('"', Math.Max(3, longest + 1));
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/> by Settings.Generators");
        sb.AppendLine("namespace Settings.Generated;");
        sb.AppendLine();
        sb.AppendLine("internal static partial class AppSchema");
        sb.AppendLine("{");
        sb.Append("    public const string Html = ").AppendLine(quotes);
        foreach (var line in html.Split('\n'))
            sb.Append("        ").AppendLine(line.TrimEnd('\r'));
        sb.Append("        ").Append(quotes).AppendLine(";");
        sb.AppendLine("}");
        return sb.ToString();
    }
}

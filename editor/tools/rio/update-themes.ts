// Regenerates schema/rio/rio-themes.json: the catalogue of Rio themes the editor can install.
//
//   node tools/rio/update-themes.ts
//
// Rio ships no themes; it loads ~/.config/rio/themes/<name>.toml. The themes come from
// mbadolato/iTerm2-Color-Schemes (MIT), whose rio/ folder holds one TOML per theme. Only that
// folder is fetched (sparse, shallow git checkout), pinned to the commit recorded in the output;
// the editor later downloads a single theme file from that same commit when the user picks it.

import { execFileSync } from "node:child_process";
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repo = "mbadolato/iTerm2-Color-Schemes";
const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const work = mkdtempSync(join(tmpdir(), "rio-themes-"));

try {
  const git = (...args: string[]) => execFileSync("git", args, { cwd: work, encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] });
  git("clone", "--quiet", "--depth", "1", "--filter=blob:none", "--sparse", `https://github.com/${repo}.git`, "src");
  const src = join(work, "src");
  execFileSync("git", ["sparse-checkout", "set", "rio"], { cwd: src, stdio: ["ignore", "ignore", "inherit"] });
  const commit = execFileSync("git", ["rev-parse", "HEAD"], { cwd: src, encoding: "utf8" }).trim();

  const ansi = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"];
  const themes = [];
  for (const file of readdirSync(join(src, "rio")).filter((f) => f.endsWith(".toml")).sort((a, b) => a.localeCompare(b))) {
    const text = readFileSync(join(src, "rio", file), "utf8");
    const color = (key: string) =>
      new RegExp(`^${key}\\s*=\\s*['"](#[0-9a-fA-F]{6})`, "m").exec(text)?.[1]?.toLowerCase() ?? null;
    const bg = color("background");
    const fg = color("foreground");
    if (!bg || !fg) continue;
    themes.push({ name: basename(file, ".toml"), bg, fg, ansi: ansi.map(color) });
  }

  const out = {
    $comment: "GENERATED by tools/rio/update-themes.ts. Theme files are downloaded from this repo/commit on demand.",
    repo,
    commit,
    path: "rio",
    license: "MIT",
    themes,
  };
  writeFileSync(join(root, "schema", "rio", "rio-themes.json"), JSON.stringify(out) + "\n");
  console.log(`rio-themes.json: ${themes.length} themes from ${repo}@${commit.slice(0, 7)}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
